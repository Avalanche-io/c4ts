// Generates packages/core/src/printable-table.ts from the shared table
// tests/fixtures/safename-vector/printable-17.0.0.txt (a byte-identical copy
// of c4 core's c4m/testdata/safename-vector/printable-17.0.0.txt).
//
//   node packages/core/scripts/gen-printable.mjs
//
// SafeName's printable test is pinned to that one table, never the runtime's
// Unicode (decided 2026-11-13 by the release lead; reversible). The test
// printable-table.test.ts fails if the generated table and the text file
// differ.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const VERSION = '17.0.0'
const here = (p) => fileURLToPath(new URL(p, import.meta.url))
const src = here(`../tests/fixtures/safename-vector/printable-${VERSION}.txt`)
const out = here('../src/printable-table.ts')

const ranges = []
for (const raw of readFileSync(src, 'utf8').split('\n')) {
  const line = raw.trim()
  if (line === '' || line.startsWith('#')) continue
  const m = /^([0-9A-F]+)\.\.([0-9A-F]+)$/.exec(line)
  if (!m) throw new Error(`bad range line: ${JSON.stringify(line)}`)
  const lo = parseInt(m[1], 16)
  const hi = parseInt(m[2], 16)
  const prev = ranges[ranges.length - 1]
  if (lo > hi || (prev && lo <= prev[1])) throw new Error(`ranges not sorted and disjoint at ${line}`)
  ranges.push([lo, hi])
}

const hex = (n) => '0x' + n.toString(16).toUpperCase().padStart(4, '0')
const body = ranges.map(([lo, hi]) => `  ${hex(lo)}, ${hex(hi)},`).join('\n')
writeFileSync(out, `// Code generated by scripts/gen-printable.mjs from
// tests/fixtures/safename-vector/printable-${VERSION}.txt. DO NOT EDIT.

/** The Unicode version SafeName's printable table is pinned to. */
export const PRINTABLE_UNICODE_VERSION = '${VERSION}'

/**
 * Go's unicode.IsPrint at Unicode ${VERSION} (letters, marks, numbers,
 * punctuation, symbols, and U+0020), as inclusive code point ranges
 * flattened to [lo0, hi0, lo1, hi1, ...], sorted and disjoint
 * (${ranges.length} ranges).
 */
export const PRINTABLE_RANGES: readonly number[] = [
${body}
]
`)
console.log(`wrote ${ranges.length} ranges to ${out}`)
